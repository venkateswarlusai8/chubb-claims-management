using Claims.Api.Domain;
using Claims.Api.Infrastructure.Auth;
using Microsoft.EntityFrameworkCore;

namespace Claims.Api.Infrastructure.Persistence;

public static class DatabaseInitializer
{
    /// <summary>Applies EF Core migrations and, if enabled and the database is empty, seeds demo claims.</summary>
    public static async Task InitialiseDatabaseAsync(this WebApplication app)
    {
        using var scope = app.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ClaimsDbContext>();
        await db.Database.MigrateAsync();

        if (app.Configuration.GetValue("Database:SeedDemoData", true) && !await db.Claims.AnyAsync())
        {
            var users = scope.ServiceProvider.GetRequiredService<IUserDirectory>();
            var now = scope.ServiceProvider.GetRequiredService<TimeProvider>().GetUtcNow().UtcDateTime;
            db.Claims.AddRange(DemoData.CreateClaims(users, now));
            await db.SaveChangesAsync();
        }
    }
}

/// <summary>
/// Demo claims built through the domain methods (not raw inserts), so history, information
/// requests and outbox events are realistic and notifications are generated by the normal pipeline.
/// </summary>
public static class DemoData
{
    public static IReadOnlyList<Claim> CreateClaims(IUserDirectory users, DateTime now)
    {
        Actor U(string id) => users.Find(id) ?? throw new InvalidOperationException($"Demo user {id} missing.");
        var asha = U("claimant-asha");
        var daniel = U("claimant-daniel");
        var mei = U("claimant-mei");
        var priya = U("officer-priya");
        var james = U("officer-james");

        DateTime Ago(double days) => now.AddDays(-days);

        Claim New(Actor claimant, string policy, string market, ClaimType type, double daysAgo, string description, decimal amount)
        {
            var submitted = Ago(daysAgo);
            return Claim.Submit(Claim.GenerateClaimNumber(submitted), claimant, policy, Markets.Find(market)!, type,
                DateOnly.FromDateTime(submitted.AddDays(-2)), description, amount, submitted);
        }

        var c1 = New(asha, "MTR-SG-100234", "SG", ClaimType.Motor, 2,
            "Rear-end collision at a junction on Orchard Road. Rear bumper and tail lights damaged.", 4200m);

        var c2 = New(daniel, "PRP-AU-550912", "AU", ClaimType.Property, 10,
            "Burst pipe in the upstairs bathroom caused water damage to the ceiling and flooring below.", 12500m);
        c2.Assign(priya, Ago(9));

        var c3 = New(mei, "MTR-HK-773410", "HK", ClaimType.Motor, 12,
            "Vehicle scraped by a reversing van in a car park; passenger door dented.", 18000m);
        c3.Assign(james, Ago(11));
        c3.RequestInformation(james, "Please provide photos of the damage and the repair quotation from your workshop.", Ago(10));

        var c4 = New(asha, "PRP-SG-200871", "SG", ClaimType.Property, 21,
            "Kitchen fire damaged cabinets and two appliances.", 25000m);
        c4.Assign(priya, Ago(20));
        c4.Approve(priya, 22000m, "Approved less policy excess and depreciation on appliances.", Ago(6));

        var c5 = New(daniel, "MTR-NZ-310045", "NZ", ClaimType.Motor, 30,
            "Windscreen cracked by a flying stone on the motorway.", 3100m);
        c5.Assign(james, Ago(29));
        c5.Approve(james, 3100m, null, Ago(25));
        c5.Settle(james, 3100m, Ago(20));

        var c6 = New(mei, "PRP-MY-640218", "MY", ClaimType.Property, 18,
            "Storm damage to the garden shed and boundary fence.", 8000m);
        c6.Assign(priya, Ago(17));
        c6.Reject(priya, "Outbuildings and fences are excluded under section 4.2 of the home policy.", Ago(12));

        var c7 = New(asha, "MTR-TH-901122", "TH", ClaimType.Motor, 20,
            "Side-swiped while parked; wing mirror and front wing damaged.", 60000m);

        var c8 = New(daniel, "MTR-AU-550913", "AU", ClaimType.Motor, 1,
            "Hail damage to roof and bonnet during a storm.", 5400m);

        var c9 = New(mei, "PRP-HK-882301", "HK", ClaimType.Property, 15,
            "Ceiling collapse after a water leak from the flat above.", 40000m);
        c9.Assign(james, Ago(14));
        var request = c9.RequestInformation(james, "Please provide the building management incident report.", Ago(12));
        c9.ProvideInformation(mei, request.Id, "Incident report from building management attached, reference BM-2291.", Ago(9));

        var c10 = New(daniel, "MTR-SG-100299", "SG", ClaimType.Motor, 16,
            "Minor collision at a roundabout; front bumper needs replacement.", 2750m);
        c10.Assign(priya, Ago(15));

        return [c1, c2, c3, c4, c5, c6, c7, c8, c9, c10];
    }
}
